function tr(value) {
  if (value === undefined || value === null) return value;
  const text = String(value);
  if (window.ffaiPreferences.language !== "en") return text;
  const compact = text.replace(/\s+/g, " ").trim();
  if (english[compact]) return english[compact];
  return text
    .replace(
      /^(.+) · (К выполнению|В работе|Готово|Заблокировано|Ожидание|Нужен ваш ответ)$/,
      (_, step, status) =>
        `${english[step] || step} · ${english[status] || status}`,
    )
    .replace(
      /^Команда ждёт вашего ответа · (\d+)$/,
      "The team needs your answer · $1",
    )
    .replace(/ → Ответить$/, " → Answer")
    .replace(/^(\d+) ждут ответа$/, "$1 awaiting an answer")
    .replace(/^(\d+) в работе$/, "$1 working")
    .replace(/^План (.+) · Тикет$/, "Plan $1 · Ticket")
    .replace(/^План (.+) · Требование$/, "Plan $1 · Requirement")
    .replace(/^План (.+)$/, "Plan $1")
    .replace(/^(\d+) вызовов · планирование (\d+)$/, "$1 calls · $2 planning")
    .replace(
      /^Ещё (\d+). Выберите план или уточните поиск.$/,
      "$1 more. Choose a plan or refine the search.",
    )
    .replace(
      /^Снимок от (.+) · (\d+) карточек · только просмотр\..+$/,
      "Snapshot $1 · $2 cards · read-only. States belong to the original orchestrator, not this engine.",
    )
    .replace(/^Шаг: (.+) · версия (\d+) · (.+)$/, "Step: $1 · version $2 · $3")
    .replace(/^Создано на паузе: /, "Created paused: ")
    .replace(/^Версия опубликована: /, "Version published: ")
    .replace(
      /^Связь: (.+)\. Её можно изменить или удалить ниже\.$/,
      "Edge: $1. Edit or remove it below.",
    )
    .replace(/^Зависит от: /, "Depends on: ")
    .replace(/ · пауза/, " · paused")
    .replace(/ \+ неизвестные/, " + unknown")
    .replace(/^Выход /, "Output ")
    .replace(/^Вход /, "Input ");
}
(() => {
  const source = new WeakMap();
  const skip = (n) =>
    n.parentElement?.closest("script,style,textarea,pre,[data-content]");
  const translate = (root) => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (skip(node) || !node.textContent.trim()) continue;
      const old = source.get(node);
      const original =
        old && old.last === node.textContent ? old.original : node.textContent;
      const translated = tr(original);
      source.set(node, { original, last: translated });
      if (node.textContent !== translated) node.textContent = translated;
    }
    root.querySelectorAll?.("[placeholder],[aria-label]").forEach((node) => {
      if (node.closest("[data-content]")) return;
      for (const attr of ["placeholder", "aria-label"])
        if (node.hasAttribute(attr)) {
          const key = "original-" + attr;
          if (!node.hasAttribute("data-" + key))
            node.setAttribute("data-" + key, node.getAttribute(attr));
          node.setAttribute(attr, tr(node.getAttribute("data-" + key)));
        }
    });
  };
  let pending = false;
  const schedule = () => {
    if (pending) return;
    pending = true;
    queueMicrotask(() => {
      pending = false;
      translate(document.body);
    });
  };
  document.addEventListener("preferences-changed", schedule);
  new MutationObserver(schedule).observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
  translate(document.body);
})();
